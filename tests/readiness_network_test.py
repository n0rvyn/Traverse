"""Actual inotify and kernel route events inside the disposable test namespaces."""
import json
from pathlib import Path
import subprocess
import socket
import struct
import sys
import tempfile
import time
from installed_managed_certificates import require_disposable_environment

def main():
    require_disposable_environment()
    with tempfile.TemporaryDirectory(prefix='readiness-network-') as name:
        root=Path(name);(root/'a').mkdir();(root/'b').mkdir()
        first=root/'a'/'resolver';second=root/'b'/'resolver'
        first.write_text('first');second.write_text('second')
        link=root/'resolver';link.symlink_to(first)
        middle=root/'middle';middle.symlink_to(root/'a',target_is_directory=True)
        missing=root/'missing'/'hosts'
        process=subprocess.Popen([sys.argv[1],str(link),str(middle/'resolver'),str(missing)],
            stdin=subprocess.PIPE,stdout=subprocess.PIPE,text=True)
        try:
            assert process.stdout.readline().strip()=='ready'
            def poll():
                process.stdin.write('poll\n');process.stdin.flush()
                line=process.stdout.readline();assert line,'Native watcher exited';return json.loads(line)
            def changed():
                end=time.monotonic()+3
                while True:
                    row=poll()
                    if row['changed']:assert row['healthy'],row;return
                    assert time.monotonic()<end,'Actual kernel/file change was missed'
                    time.sleep(.001)
            assert poll()==dict(changed=False,healthy=True)
            first.write_text('changed');changed()
            replacement=root/'replacement';replacement.symlink_to(second);replacement.replace(link);changed()
            second.write_text('new target');changed()
            middle.unlink();middle.symlink_to(root/'b',target_is_directory=True);changed()
            second.write_text('intermediate target');changed()
            missing.parent.mkdir();changed();missing.write_text('created');changed()
            (root/'unrelated').write_text('ignored');assert poll()==dict(changed=False,healthy=True)
            # The runner owns this dummy interface in the verified private
            # network namespace. Use the real kernel API without an ip CLI dependency.
            index=socket.if_nametoindex('traverse-test0')
            def attribute(kind,value):
                size=4+len(value);return struct.pack('=HH',size,kind)+value+b'\0'*((-size)%4)
            def netlink(kind,body,flags=0):
                with socket.socket(socket.AF_NETLINK,socket.SOCK_RAW,socket.NETLINK_ROUTE) as channel:
                    channel.settimeout(3);channel.bind((0,0))
                    channel.sendto(struct.pack('=IHHII',16+len(body),kind,1|4|flags,1,0)+body,(0,0))
                    reply=channel.recv(65536)
                    assert struct.unpack_from('=H',reply,4)[0]==2,reply
                    assert struct.unpack_from('=i',reply,16)[0]==0,reply
            def link(up):netlink(16,struct.pack('=BBHiII',0,0,0,index,int(up),1))
            address=struct.pack('=BBBBI',socket.AF_INET,24,0,0,index)+attribute(2,socket.inet_aton('198.18.0.1'))+attribute(1,socket.inet_aton('198.18.0.1'))
            route=struct.pack('=BBBBBBBBI',socket.AF_INET,24,0,0,254,4,253,1,0)+attribute(1,socket.inet_aton('198.19.0.0'))+attribute(4,struct.pack('=I',index))
            link(False)
            try:
                changed();link(True);changed()
                netlink(20,address,0x400|0x200);changed()
                netlink(24,route,0x400|0x200);changed()
                netlink(25,route);changed()
                netlink(21,address);changed()
            finally:link(True)
            # Drain the finite kernel messages generated by the link/route fixture.
            while poll()['changed']:pass
            limit=int(Path('/proc/sys/fs/inotify/max_queued_events').read_text())
            for number in range(limit+1):(root/('burst-'+str(number))).touch()
            result=poll();assert result==dict(changed=True,healthy=False),result
            print('Actual resolver writes/replacement/symlink targets/missing files, kernel link/address/route events and queue overflow passed')
        finally:
            process.stdin.close();process.wait(timeout=5);process.stdout.close()
            assert process.returncode==0,process.returncode

if __name__=='__main__':main()
